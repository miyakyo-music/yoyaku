function table(widths, rows, head = true) {
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, i) => new TableRow({
      tableHeader: head && i === 0,
      children: r.map((c, j) => new TableCell({
        borders,
        width: { size: widths[j], type: WidthType.DXA },
        shading: head && i === 0 ? { fill: 'EDEDED', type: ShadingType.CLEAR, color: 'auto' } : undefined,
        margins: { top: 80, bottom: 80, left: 120, right: 120 },
        children: [new Paragraph({ spacing: { line: 300 }, children: [head && i === 0 ? b(c) : t(c)] })],
      })),
    })),
  });
}
function box(children) {
  const bd = { style: BorderStyle.SINGLE, size: 12, color: '1F5FA8' };
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    rows: [new TableRow({ children: [new TableCell({
      borders: { top: bd, bottom: bd, left: bd, right: bd },
      width: { size: W, type: WidthType.DXA },
      shading: { fill: 'EEF4FB', type: ShadingType.CLEAR, color: 'auto' },
      margins: { top: 160, bottom: 160, left: 240, right: 240 },
      children,
    })] })],
  });
}
